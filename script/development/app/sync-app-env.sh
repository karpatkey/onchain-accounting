#!/usr/bin/env bash
# Rewrite app/.env.local so the Next.js dashboard reads from local anvil forks instead of
# live Alchemy endpoints. Run after start-forks.sh + deploy.sh.
#
# Writes a per-chain NEXT_PUBLIC_NAV_ADDRESS_<chainId> for every chain, since dev forks deploy
# via plain CREATE — the proxy address depends on the deployer EOA's nonce on each fork, and
# the forked nonces inherit from the live chains (not zero).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
DEV_DIR="$REPO_ROOT/script/development"
STATE_DIR="$DEV_DIR/state"
CONFIG="$DEV_DIR/config/chains.json"
ENV_LOCAL="$REPO_ROOT/app/.env.local"

if [ ! -d "$STATE_DIR" ]; then
  echo "error: $STATE_DIR not found — run start-forks.sh + deploy.sh first" >&2
  exit 1
fi

# Pre-flight: every chain has an addresses file with a NAV proxy
for cid in $(jq -r 'keys[]' "$CONFIG"); do
  addr_file="$STATE_DIR/$cid-addresses.json"
  if [ ! -f "$addr_file" ]; then
    echo "error: $addr_file missing — deploy.sh hasn't run for chain $cid" >&2
    exit 1
  fi
  this=$(jq -r '.NAVCalculatorProxy // ""' "$addr_file")
  if [ -z "$this" ]; then
    echo "error: chain $cid addresses file has no NAVCalculatorProxy" >&2
    exit 1
  fi
done

{
  echo "# Generated by script/development/app/sync-app-env.sh — points the app at local anvil forks."
  echo "# To switch back to live RPCs, restore from .env (MAINNET_URL, etc.) + clear the NAV_ADDRESS_* vars."
  for cid in $(jq -r 'keys[]' "$CONFIG"); do
    port=$(jq -r ".\"$cid\".port" "$CONFIG")
    proxy=$(jq -r '.NAVCalculatorProxy' "$STATE_DIR/$cid-addresses.json")
    echo "NEXT_PUBLIC_RPC_URL_$cid=http://127.0.0.1:$port"
    echo "NEXT_PUBLIC_NAV_ADDRESS_$cid=$proxy"
  done
  echo "NEXT_PUBLIC_AUTOREFRESH_INTERVAL_MIN="
} > "$ENV_LOCAL"

echo "wrote $ENV_LOCAL:"
grep -E "^NEXT_PUBLIC_NAV_ADDRESS_|^NEXT_PUBLIC_RPC_URL_" "$ENV_LOCAL"
echo
echo "restart the Next.js dev server so it picks up the new env."
